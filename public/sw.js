// Service worker: makes the portal installable and shows a friendly page when offline.
// It deliberately does NOT cache committee pages or files, so private data never sits in the phone's cache.
const CACHE = "hoa-shell-v1";
const SHELL = ["/offline.html", "/icons/icon-192.png"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || req.mode !== "navigate") return; // only page loads
  event.respondWith(fetch(req).catch(() => caches.match("/offline.html")));
});
